"""Summarise Exp 4 into ``summary.json`` and ``summary_tables.md`` (results/exp4_published_model).

    source experiments/exp4_published_model/env.sh; exp4py experiments/exp4_published_model/analyse_exp4.py

A. Do the 17 numbers come back? Per arrow over the no-subgroup runs: mean, SD and 95% range of the PLS estimate,
   how often it keeps the published sign and how often it is significant (|estimate / SE| >= 1.96), and whether the
   real data's PLS estimate falls inside the 95% range (if not, the gap is the method's, not luck's).
B. What does EMM report when no subgroup exists? Share of runs with any finding, the top-score distribution, the
   p-value of the real top score, how often the real findings appear, and how the chance findings would change the
   conclusion about feedback -> achievement.
C. Would a real finding be found again? Per planted World: recovery, rank, found vs planted gap.
"""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pandas as pd

OUT = Path(__file__).resolve().parents[1] / "results" / "exp4_published_model"
PATH = "feedback -> Achievement"
EPS = 1e-9


def se(p: float, n: int) -> float:
    return float(np.sqrt(p * (1 - p) / n)) if n else float("nan")


def main() -> None:
    coefs = pd.read_csv(OUT / "coefs.csv")
    runs = pd.read_csv(OUT / "runs.csv")
    finds = pd.read_csv(OUT / "findings.csv")
    real_fit = pd.read_csv(OUT / "real_fit.csv", index_col=0)
    real_find = pd.read_csv(OUT / "real_findings.csv")
    planted = json.loads((OUT / "planted.json").read_text())["planted"]
    s: dict = {}

    rows = []
    for path, g in coefs.groupby("path"):
        pub = float(real_fit.loc[path, "published"])
        lo, hi = g.estimate.quantile([0.025, 0.975])
        realv = float(real_fit.loc[path, "estimate"])
        rows.append({"path": path, "published": pub, "runs": len(g), "mean": g.estimate.mean(), "sd": g.estimate.std(),
                     "lo95": lo, "hi95": hi, "same_sign": float((np.sign(g.estimate) == np.sign(pub)).mean()),
                     "significant": float(((g.estimate / g.se).abs() >= 1.96).mean()), "real_pls": realv,
                     "real_inside_range": bool(lo <= realv <= hi)})
    A = pd.DataFrame(rows).set_index("path").loc[real_fit.index]
    s["A"] = A.reset_index().to_dict("records")

    n0 = runs[runs.world == "no_subgroups"]
    q_real = float(real_find.quality.iloc[0]) if len(real_find) else 0.0
    hits = int((n0.top_quality >= q_real - EPS).sum())
    f0 = finds[finds.world == "no_subgroups"]
    flip = f0[np.sign(f0.estimate_sg) != np.sign(f0.estimate_complement)]
    s["B"] = {"runs": len(n0), "share_any_finding": float((n0.n_findings > 0).mean()),
              "mean_findings": float(n0.n_findings.mean()), "q95_top_quality": float(n0.top_quality.quantile(0.95)),
              "real_top_quality": q_real, "runs_at_least_real": hits, "p_value": (1 + hits) / (1 + len(n0)),
              "share_at_least_real_count": float((n0.n_findings >= len(real_find)).mean()),
              "listed_real": {k.replace("listed_", ""): float(n0[k].astype(bool).mean())
                              for k in n0.columns if k.startswith("listed_")},
              "top_descriptions": n0.top_description.fillna("(none)").value_counts().head(8).to_dict(),
              "chance_findings": len(f0), "chance_findings_sign_flip": len(flip),
              "chance_mean_abs_gap": float((f0.estimate_sg - f0.estimate_complement).abs().mean()) if len(f0) else 0.0,
              "top_quality_values": n0.top_quality.round(4).tolist()}

    s["C"] = {}
    for w, meta in planted.items():
        r = runs[runs.world == w]
        rec = r[r.recovered.astype(bool)]
        gap_planted = meta["inside"] - meta["outside"]
        p = float(len(rec) / len(r)) if len(r) else float("nan")
        s["C"][w] = {"description": meta["description"], "size": meta["size"], "runs": len(r), "recovered": p,
                     "recovered_se": se(p, len(r)), "top_is_planted": float(r.top_is_planted.astype(bool).mean()),
                     "rank_counts": rec.match_rank.astype(int).value_counts().sort_index().to_dict(),
                     "planted_inside": meta["inside"], "planted_outside": meta["outside"], "planted_gap": gap_planted,
                     "estimated_gap_all_runs": float((r.planted_inside_est - r.planted_outside_est).mean()),
                     "intervals_disjoint": float(r.planted_disjoint.astype(bool).mean()),
                     "found_gap": float((rec.match_estimate_sg - rec.match_estimate_rest).mean()) if len(rec) else None,
                     "unrelated_per_run": float(r.n_unrelated.mean())}
    (OUT / "summary.json").write_text(json.dumps(s, indent=1, default=float))

    L = ["# Experiment 4 summary tables (generated by analyse_exp4.py)", "",
         "## A. Do the published numbers come back? (no-subgroup recipe, PLS on each fake Greece)", "",
         "| arrow | published | mean | SD | 95% range | same sign | significant | real PLS | real inside range |",
         "|---|---|---|---|---|---|---|---|---|"]
    for path, r in A.iterrows():
        L.append(f"| {path} | {r.published:.3f} | {r['mean']:.3f} | {r.sd:.3f} | {r.lo95:.3f} to {r.hi95:.3f} | "
                 f"{r.same_sign:.0%} | {r.significant:.0%} | {r.real_pls:.3f} | "
                 f"{'yes' if r.real_inside_range else 'no'} |")
    B = s["B"]
    L += ["", "## B. What EMM reports when no subgroup exists", "",
          f"- runs: {B['runs']}; runs with any finding: {B['share_any_finding']:.0%}; findings per run: "
          f"{B['mean_findings']:.2f}",
          f"- real top score {B['real_top_quality']:.4f}: reached in {B['runs_at_least_real']} runs, "
          f"p = {B['p_value']:.3f};"
          f" 95% chance threshold {B['q95_top_quality']:.3f}",
          f"- real findings listed by chance: {B['listed_real']}",
          f"- chance findings with the subgroup's slope of the opposite sign to the rest: "
          f"{B['chance_findings_sign_flip']} of {B['chance_findings']}", "",
          "## C. Planted: each real finding true by construction", "",
          "| planted subgroup | students | runs | found again (SE) | rank 1 | planted gap | intervals disjoint |"
          " found gap (when found) |", "|---|---|---|---|---|---|---|---|"]
    for c in s["C"].values():
        fg = f"{c['found_gap']:.3f}" if c["found_gap"] is not None else "-"
        L.append(f"| {c['description']} | {c['size']} | {c['runs']} | {c['recovered']:.0%} ({c['recovered_se']:.0%}) | "
                 f"{c['top_is_planted']:.0%} | {c['planted_gap']:.3f} | {c['intervals_disjoint']:.0%} | {fg} |")
    (OUT / "summary_tables.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
